import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {validateSnapshot,margin,boardForecast,roadForecast,snap,usableAccuracy,clock,stops} from './dist/web/core.js';
const seed=JSON.parse(await readFile(new URL('./web/seed.json',import.meta.url)));
validateSnapshot(seed);
const bad=structuredClone(seed);bad.data.routes[0].events[0].minute=1440;
assert.throws(()=>validateSnapshot(bad),/Horário/);
assert.deepEqual(margin({name:'Tabatinga'},0,376),{early:372,late:380});
assert.deepEqual(margin({name:'Tabatinga'},1,376),{early:372,late:378});
assert.deepEqual(margin({name:'Umarizeiras'},1,376),{early:376,late:376});
assert.deepEqual([99,100,101].map(usableAccuracy),[true,true,false]);
assert.equal(usableAccuracy(NaN),false);
assert.equal(clock(new Date('2026-10-14T09:16:00Z')).minute,376);
const data={stops:[{name:'Saída'},{name:'Rodoviária'},{name:'Pau Serrado'},{name:'Shopping'}],routes:[{name:'Tabatinga',confirmed:true,events:[{stop:1,minute:376,destination:'Shopping',vehicle:'5º carro'}],roadSegments:[{from:1,to:3,destination:'Shopping',travelMinutes:10,itineraryConfirmed:true,path:[[0,0],[0,.01]]}]}]};
assert.equal(boardForecast(data,'stop:Rodoviária','','',378)[0].future.length,1);
assert.equal(boardForecast(data,'stop:Rodoviária','','',378.01)[0].future.length,0);
const mid=roadForecast(data,0,.005,370);
assert.equal(mid.directions[0].future[0].reference,381);
assert.equal(mid.directions[0].future[0].late,383);
// A street 13 m away cannot replace the confirmed bus road 400+ m away.
const other=structuredClone(data);other.routes[0].roadSegments.push({...other.routes[0].roadSegments[0],itineraryConfirmed:false,path:[[.0036,0],[.0036,.01]]});
const outside=roadForecast(other,.0037,.005,370);
assert.equal(outside.directions.length,0);
assert.ok(outside.nearest.snap.distance>400);
assert.equal(snap(0,.005,[[0,0],[0,.01]]).fraction,.5);
assert.equal(snap(0,.005,[[0,0],[0,.01],[0,.02]],[90,10]).fraction,.45);
assert.equal(snap(0,0,[[0,0],[0,0]]),null);
const origin=structuredClone(data);origin.routes[0].origin={lat:0,lon:0,id:'untrusted',name:'wrong'};
assert.equal(stops(origin)[0].id,'origin:Tabatinga');
console.log('PASS: web validation, Ceará clock, timing margins, GPS accuracy and confirmed-route projection');
